def get_powershell_executable() -> str:
    system_root = os.environ.get("SystemRoot") or r"C:\Windows"
    candidate = Path(system_root) / "System32" / "WindowsPowerShell" / "v1.0" / "powershell.exe"
    if candidate.exists():
        return str(candidate)
    return "powershell.exe"


def get_dead_pid() -> int:
    """Launch a quick Python pass process and wait for it to exit, returning its dead PID."""
    proc = subprocess.Popen([sys.executable, "-c", "pass"])
    proc.wait()
    return proc.pid


def snapshot_tree(root: Path) -> Dict[str, str]:
    """Capture a mapping of relative paths to SHA-256 digests for all files in a tree."""
    tree: Dict[str, str] = {}
    if not root.exists():
        return tree
    for p in sorted(root.rglob("*")):
        if p.is_file():
            rel = str(p.relative_to(root)).replace("\\", "/")
            h = hashlib.sha256(p.read_bytes()).hexdigest()
            tree[rel] = h
    return tree


