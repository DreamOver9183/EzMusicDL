def run_script_with_overrides(
    script_text: str,
    tmp_path: Path,
    app_root: Path,
    staging_dir: Path,
    payload_root: Path,
    log_path: Path,
    fallback_log_path: Path,
    overrides: str = "",
    timeout: int = 90,
) -> subprocess.CompletedProcess:
    """Safely validate path isolation, inject default guards, apply overrides, and execute script."""
    # Mandatory Safety Assertions: All paths must reside within tmp_path
    tmp_resolved = str(tmp_path.resolve()).lower()
    for name, p in [
        ("app_root", app_root),
        ("staging_dir", staging_dir),
        ("payload_root", payload_root),
        ("log_path", log_path),
        ("fallback_log_path", fallback_log_path),
    ]:
        p_resolved = str(p.resolve()).lower()
        assert p_resolved.startswith(tmp_resolved), f"Path {name} ({p}) violates isolation: outside {tmp_path}"

    evidence_dir = tmp_path / "evidence"
    evidence_dir.mkdir(parents=True, exist_ok=True)
    popup_record_file = evidence_dir / "popup_record.txt"
    unexpected_launch_file = evidence_dir / "unexpected_launch.txt"

    default_popup_override = f"""
function Show-UpdaterPopup([string]$text, [string]$title, [int]$icon) {{
    $out = "TITLE: $title`nICON: $icon`nTEXT: $text"
    [System.IO.File]::WriteAllText({_ps_quote(str(popup_record_file))}, $out)
}}
"""
    default_launch_guard = f"""
function Invoke-LaunchProcess([string]$exe, [string]$workDir) {{
    [System.IO.File]::WriteAllText({_ps_quote(str(unexpected_launch_file))}, "UNEXPECTED LAUNCH: $exe in $workDir")
    throw 'SAFETY-GUARD: real launch blocked'
}}
"""
    combined_overrides = default_popup_override + "\n" + default_launch_guard + "\n" + overrides

    main_marker = "# --- main ---"
    assert script_text.count(main_marker) == 1, "Script must contain exactly one '# --- main ---' line"

    # Insert overrides directly before the isolated # --- main --- line
    modified_script = script_text.replace(main_marker, combined_overrides + "\n" + main_marker)

    script_path = staging_dir / "test_updater.ps1"
    script_path.write_text(modified_script, encoding="utf-8-sig")

    ps_exe = get_powershell_executable()
    creation_flags = getattr(subprocess, "CREATE_NO_WINDOW", 0x08000000)

    return subprocess.run(
        [
            ps_exe,
            "-NoProfile",
            "-ExecutionPolicy",
            "Bypass",
            "-File",
            str(script_path),
        ],
        capture_output=True,
        timeout=timeout,
        creationflags=creation_flags,
    )


